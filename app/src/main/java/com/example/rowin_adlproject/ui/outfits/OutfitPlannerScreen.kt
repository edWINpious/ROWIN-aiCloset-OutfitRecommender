/**
 * Features #8-#9, #12, #21: Outfit Planner. Slot canvas (Outerwear/Top/
 * Bottom/Shoes/Accessories), tap-to-pick from the wardrobe, "Generate Outfit"
 * (Groq AI), name + season + occasion, and Save/Update.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun OutfitPlannerScreen(
    userId: Long,
    editingOutfitId: Long?,
    onSaved: (Long) -> Unit,
    onBack: (() -> Unit)? = null,
) {
    val context = LocalContext.current
    val factory = remember(userId, editingOutfitId) { PlannerViewModel.Factory(context, userId, editingOutfitId) }
    val vm: PlannerViewModel = viewModel(key = "planner-${editingOutfitId ?: 0}", factory = factory)

    val editing by vm.editingOutfit.collectAsState()
    val wardrobe by vm.wardrobe.collectAsState()
    val generating by vm.generating.collectAsState()
    val generated by vm.generated.collectAsState()
    val generationNote by vm.generationNote.collectAsState()
    val outfitName by vm.outfitName.collectAsState()
    val outfitSeason by vm.outfitSeason.collectAsState()
    val outfitOccasion by vm.outfitOccasion.collectAsState()

    var pickerSlot by remember { mutableStateOf<PlannerViewModel.Slot?>(null) }
    var saveError by remember { mutableStateOf<String?>(null) }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .imePadding(),
    ) {
        if (onBack != null) {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 12.dp, vertical = 8.dp),
                verticalAlignment = Alignment.CenterVertically,
            ) {
                IconButton(onClick = onBack) {
                    Icon(imageVector = RowinIcons.Back, contentDescription = "Back")
                }
                Text(
                    text = if (editing == null) "Outfit Planner" else "Edit Outfit",
                    style = MaterialTheme.typography.headlineMedium,
                    color = MaterialTheme.colorScheme.onSurface,
                    modifier = Modifier.weight(1f),
                    textAlign = TextAlign.Center,
                )
                Spacer(Modifier.size(48.dp))
            }
        } else {
            Column(modifier = Modifier.padding(horizontal = 20.dp, vertical = 16.dp)) {
                Text(
                    text = "Outfit Planner",
                    style = MaterialTheme.typography.headlineLarge,
                    color = MaterialTheme.colorScheme.onSurface,
                )
                Text(
                    text = "Build a look from your wardrobe.",
                    style = MaterialTheme.typography.bodyMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        }

        Column(modifier = Modifier.padding(horizontal = 20.dp)) {
            // Slot canvas
            PlannerViewModel.Slot.entries.forEach { slot ->
                OutfitSlot(
                    slot = slot,
                    item = vm.selectionForSlot(slot)?.let { id -> wardrobe.firstOrNull { it.id == id } },
                    imageFileFor = vm::imageFileFor,
                    onPick = { pickerSlot = slot },
                    onClear = { vm.selectInSlot(slot, null) },
                )
                Spacer(Modifier.height(12.dp))
            }

            // Generated suggestions strip
            if (generated.isNotEmpty()) {
                Text(
                    text = "AI Suggestions",
                    style = MaterialTheme.typography.titleMedium,
                    color = MaterialTheme.colorScheme.onSurface,
                    modifier = Modifier.padding(top = 12.dp, bottom = 4.dp),
                )
                generationNote?.let {
                    Text(
                        text = it,
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.padding(bottom = 8.dp),
                    )
                }
                generated.forEach { suggestion ->
                    Surface(
                        onClick = { vm.applySuggestion(suggestion) },
                        shape = RoundedCornerShape(12.dp),
                        color = MaterialTheme.colorScheme.surfaceContainerLowest,
                        border = androidx.compose.foundation.BorderStroke(1.dp, MaterialTheme.colorScheme.outlineVariant),
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(vertical = 4.dp),
                    ) {
                        Column(modifier = Modifier.padding(12.dp)) {
                            Text(
                                text = suggestion.name,
                                style = MaterialTheme.typography.labelLarge,
                                color = MaterialTheme.colorScheme.primary,
                            )
                            Text(
                                text = "${suggestion.itemIds.size} pieces - ${suggestion.occasion.displayName()}",
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                            )
                        }
                    }
                }
            }

            // Outfit info (name + season + occasion, per the mock layout)
            Spacer(Modifier.height(16.dp))
            RowinTextField(
                value = outfitName,
                onValueChange = { vm.outfitName.value = it },
                label = "Outfit Name",
                placeholder = "e.g. Spring Office Look",
            )
            Spacer(Modifier.height(12.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(16.dp), modifier = Modifier.fillMaxWidth()) {
                Box(modifier = Modifier.weight(1f)) {
                    RowinDropdown(
                        label = "Season",
                        options = com.example.rowin_adlproject.data.Season.entries.map { it.displayName() },
                        selectedIndex = com.example.rowin_adlproject.data.Season.entries.indexOf(outfitSeason),
                        onSelect = { vm.outfitSeason.value = com.example.rowin_adlproject.data.Season.entries[it] },
                    )
                }
                Box(modifier = Modifier.weight(1f)) {
                    RowinDropdown(
                        label = "Occasion",
                        options = com.example.rowin_adlproject.data.Occasion.entries.map { it.displayName() },
                        selectedIndex = com.example.rowin_adlproject.data.Occasion.entries.indexOf(outfitOccasion),
                        onSelect = { vm.outfitOccasion.value = com.example.rowin_adlproject.data.Occasion.entries[it] },
                    )
                }
            }

            if (saveError != null) {
                Text(
                    text = saveError!!,
                    color = MaterialTheme.colorScheme.error,
                    style = MaterialTheme.typography.bodySmall,
                    modifier = Modifier.padding(top = 12.dp),
                )
            }

            // Actions, in the mock's order: Generate Outfit then Save Outfit
            Spacer(Modifier.height(20.dp))
            RowinOutlinedButton(
                text = if (generating) "Generating..." else "Generate Outfit",
                onClick = vm::generateOutfits,
                enabled = !generating,
            )
            Spacer(Modifier.height(8.dp))
            RowinButton(
                text = if (editing == null) "Save Outfit" else "Update Outfit",
                onClick = {
                    vm.save(onSaved = { onSaved(it) }, onError = { saveError = it })
                },
            )
            Spacer(Modifier.height(32.dp))
        }
    }

    // Item picker bottom sheet per slot
    pickerSlot?.let { slot ->
        val options = vm.wardrobeForSlot(slot)
        ModalBottomSheet(
            onDismissRequest = { pickerSlot = null },
            containerColor = MaterialTheme.colorScheme.surface,
        ) {
            SlotPickerSheet(
                slotLabel = slot.label,
                options = options,
                selectedId = vm.selectionForSlot(slot),
                imageFileFor = vm::imageFileFor,
                onSelect = { item ->
                    vm.selectInSlot(slot, item.id)
                    pickerSlot = null
                },
                onClear = {
                    vm.selectInSlot(slot, null)
                    pickerSlot = null
                },
            )
        }
    }
}

@Composable
private fun OutfitSlot(
    slot: PlannerViewModel.Slot,
    item: ClothingItemEntity?,
    imageFileFor: (ClothingItemEntity) -> File?,
    onPick: () -> Unit,
    onClear: () -> Unit,
) {
    Box(
        modifier = Modifier
            .fillMaxWidth()
            .aspectRatio(if (slot == PlannerViewModel.Slot.TOP || slot == PlannerViewModel.Slot.BOTTOM) 4f / 3f else 21f / 9f)
            .clip(RoundedCornerShape(14.dp))
            .background(
                if (item == null) MaterialTheme.colorScheme.surfaceContainer
                else MaterialTheme.colorScheme.surfaceContainerLowest,
            )
            .border(
                1.dp,
                if (item == null) MaterialTheme.colorScheme.outlineVariant else MaterialTheme.colorScheme.primaryContainer,
                RoundedCornerShape(14.dp),
            )
            .clickable(onClick = onPick),
        contentAlignment = Alignment.Center,
    ) {
        if (item == null) {
            Column(horizontalAlignment = Alignment.CenterHorizontally) {
                Icon(
                    imageVector = RowinIcons.Add,
                    contentDescription = null,
                    tint = MaterialTheme.colorScheme.outline,
                    modifier = Modifier.size(28.dp),
                )
                Text(
                    text = if (slot.optional) "${slot.label} (Optional)" else slot.label,
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    modifier = Modifier.padding(top = 6.dp),
                )
            }
        } else {
            val file = imageFileFor(item)
            if (file != null) {
                AsyncImage(
                    model = file,
                    contentDescription = item.name,
                    contentScale = ContentScale.Crop,
                    modifier = Modifier.fillMaxSize(),
                )
            } else {
                Text(
                    text = item.name,
                    style = MaterialTheme.typography.titleMedium,
                    color = MaterialTheme.colorScheme.onSurface,
                )
            }
            // Slot label chip + clear button
            Surface(
                shape = RoundedCornerShape(8.dp),
                color = MaterialTheme.colorScheme.surfaceContainerLowest.copy(alpha = 0.9f),
                modifier = Modifier
                    .align(Alignment.BottomStart)
                    .padding(10.dp),
            ) {
                Text(
                    text = slot.label,
                    style = MaterialTheme.typography.labelSmall,
                    color = MaterialTheme.colorScheme.onSurface,
                    modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp),
                )
            }
            Surface(
                onClick = onClear,
                shape = CircleShape,
                color = MaterialTheme.colorScheme.surfaceContainerLowest.copy(alpha = 0.9f),
                modifier = Modifier
                    .align(Alignment.TopEnd)
                    .padding(10.dp)
                    .size(28.dp),
            ) {
                Box(contentAlignment = Alignment.Center) {
                    Icon(
                        imageVector = RowinIcons.Close,
                        contentDescription = "Remove ${slot.label}",
                        modifier = Modifier.size(16.dp),
                        tint = MaterialTheme.colorScheme.onSurface,
                    )
                }
            }
        }
    }
}

@Composable
private fun SlotPickerSheet(
    slotLabel: String,
    options: List<ClothingItemEntity>,
    selectedId: Long?,
    imageFileFor: (ClothingItemEntity) -> File?,
    onSelect: (ClothingItemEntity) -> Unit,
    onClear: () -> Unit,
) {
    Column(
        modifier = Modifier
            .fillMaxWidth()
            .navigationBarsPadding()
            .padding(bottom = 24.dp),
    ) {
        Text(
            text = "Choose $slotLabel",
            style = MaterialTheme.typography.titleMedium,
            color = MaterialTheme.colorScheme.onSurface,
            modifier = Modifier.padding(horizontal = 20.dp, vertical = 8.dp),
        )
        if (options.isEmpty()) {
            Text(
                text = "No items in this category yet. Add some to your closet first.",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.outline,
                modifier = Modifier.padding(horizontal = 20.dp, vertical = 16.dp),
            )
        } else {
            LazyRow(
                contentPadding = androidx.compose.foundation.layout.PaddingValues(horizontal = 20.dp),
                horizontalArrangement = Arrangement.spacedBy(12.dp),
            ) {
                items(options, key = { it.id }) { item ->
                    Box(
                        modifier = Modifier
                            .size(120.dp)
                            .clip(RoundedCornerShape(12.dp))
                            .background(MaterialTheme.colorScheme.surfaceContainerLow)
                            .border(
                                width = if (item.id == selectedId) 2.dp else 1.dp,
                                color = if (item.id == selectedId) MaterialTheme.colorScheme.primary
                                else MaterialTheme.colorScheme.surfaceVariant,
                                shape = RoundedCornerShape(12.dp),
                            )
                            .clickable { onSelect(item) },
                        contentAlignment = Alignment.Center,
                    ) {
                        val file = imageFileFor(item)
                        if (file != null) {
                            AsyncImage(
                                model = file,
                                contentDescription = item.name,
                                contentScale = ContentScale.Crop,
                                modifier = Modifier.fillMaxSize(),
                            )
                        } else {
                            Text(
                                text = item.name,
                                style = MaterialTheme.typography.labelSmall,
                                color = MaterialTheme.colorScheme.onSurface,
                                textAlign = TextAlign.Center,
                                modifier = Modifier.padding(8.dp),
                            )
                        }
                    }
                }
            }
        }
        if (selectedId != null) {
            RowinOutlinedButton(
                text = "Clear selection",
                onClick = onClear,
                modifier = Modifier.padding(horizontal = 20.dp, vertical = 12.dp),
            )
        }
    }
}
